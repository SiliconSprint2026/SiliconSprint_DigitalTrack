#!/usr/bin/env python3
"""Cache design-space sweep for the bonus track (problem statement Section 8).

For every selected configuration this script
  1. generates cva6/core/include/sweep_<name>_config_pkg.sv from the frozen
     configuration, changing ONLY the cache parameters,
  2. builds a separate Verilator model (cva6/work-ver-<name>) with the frozen
     main-memory latency,
  3. runs every kernel in tests/build/kernels/ and collects the PERF lines,
  4. writes sweep_out/results.csv (+ plots if matplotlib is available).

  tools/cache_sweep.py --configs base,d16w4_wt,d16w4_wb,d8w2_wt
  tools/cache_sweep.py --all --mem-latency 40 -j 8

Cache RTL must not be modified (rule 13.5); only the parameters below change.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import simlib  # noqa: E402
from cost_model import total_kib  # noqa: E402

REPO = simlib.REPO
BASE_CFG = simlib.CVA6_DIR / "core" / "include" / f"{simlib.DEFAULT_TARGET}_config_pkg.sv"
FROZEN_MEM_LATENCY = 40      # organizers: freeze this value before release
DEFAULT_BUDGET_KIB = 40.0    # organizers: freeze this value before release

PARAMS = {
    "dcache_kib": ("CVA6ConfigDcacheByteSize", lambda v: str(v * 1024)),
    "dcache_ways": ("CVA6ConfigDcacheSetAssoc", str),
    "line_bits": ("CVA6ConfigDcacheLineWidth", str),
    "wbuf_depth": ("CVA6ConfigWtDcacheWbufDepth", str),
    "icache_kib": ("CVA6ConfigIcacheByteSize", lambda v: str(v * 1024)),
    "icache_ways": ("CVA6ConfigIcacheSetAssoc", str),
}


def gen_config(cfg: dict) -> str:
    text = BASE_CFG.read_text()
    for key, (param, fmt) in PARAMS.items():
        if key in cfg:
            text, n = re.subn(rf"(localparam {param} = )[^;]+;", rf"\g<1>{fmt(cfg[key])};", text)
            assert n == 1, f"parameter {param} not found"
    text, n = re.subn(r"(CVA6ConfigDcacheType = )config_pkg::\w+;",
                      rf"\g<1>config_pkg::{cfg.get('dcache_type', 'WT')};", text)
    assert n == 1
    name = f"sweep_{cfg['name']}"
    (simlib.CVA6_DIR / "core" / "include" / f"{name}_config_pkg.sv").write_text(
        f"// GENERATED by tools/cache_sweep.py - do not edit\n{text}")
    return name


def build(cfg: dict, mem_latency: int, jobs: int, out: Path) -> Path | None:
    name = gen_config(cfg)
    ver = simlib.CVA6_DIR / f"work-ver-{cfg['name']}"
    log = out / f"build_{cfg['name']}.log"
    with open(log, "w") as f:
        rc = subprocess.run(["make", "-C", str(simlib.CVA6_DIR), "verilate",
                             f"TARGET_CFG={name}", f"ver-library={ver.name}",
                             f"defines=MEM_LATENCY={mem_latency}", f"NUM_JOBS={jobs}"],
                            stdout=f, stderr=subprocess.STDOUT).returncode
    binary = ver / "Variane_testharness"
    if rc != 0 or not binary.exists():
        print(f"  build FAILED for {cfg['name']} (see {log})")
        return None
    return ver


PERF_RE = re.compile(r"PERF kernel=(\S+) variant=(\S+) (.*)")


def run_kernels(cfg: dict, ver: Path, out: Path, timeout: float, jobs: int) -> list[dict]:
    from concurrent.futures import ThreadPoolExecutor
    elfs = sorted((REPO / "tests" / "build" / "kernels").glob("*.elf"))
    with ThreadPoolExecutor(max_workers=jobs) as ex:
        runs = list(ex.map(lambda e: simlib.run_rtl(
            e, out / "runs" / cfg["name"] / e.stem, timeout=timeout, ver_dir=ver), elfs))
    rows = []
    for elf, r in zip(elfs, runs):
        vec_status = "n/a"
        for line in r.log.splitlines():
            if line.startswith("KERNEL "):
                vec_status = line.split("vector=")[-1]
        for line in r.log.splitlines():
            m = PERF_RE.search(line)
            if not m:
                continue
            if m.group(2) == "vector" and vec_status == "not_implemented":
                continue
            try:
                kv = {k: int(v) for k, v in (x.split("=") for x in m.group(3).split())}
                kv = {k: kv[k] for k in ("cycles", "instret", "icache_miss", "dcache_miss",
                                         "icache_access", "dcache_access")}
            except (ValueError, KeyError):
                print(f"  {cfg['name']}: unparsable PERF line in {elf.stem}: {line[:80]}")
                continue
            row = {"config": cfg["name"], "kernel": m.group(1), "variant": m.group(2),
                   **kv, "run_status": r.status, "vector_check": vec_status}
            row["ipc"] = round(row["instret"] / row["cycles"], 3) if row["cycles"] else 0
            row["dcache_miss_rate"] = round(row["dcache_miss"] / row["dcache_access"], 4) \
                if row["dcache_access"] else 0
            rows.append(row)
        print(f"  {cfg['name']:>16} {elf.stem:<14} {r.status} ({r.seconds:.0f}s)")
    return rows


def plot(rows: list[dict], out: Path) -> None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not available - skipping plots")
        return
    kernels = sorted({r["kernel"] for r in rows})
    configs = list(dict.fromkeys(r["config"] for r in rows))
    for k in kernels:
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4))
        for variant in ("scalar", "vector"):
            ys = [next((r["cycles"] for r in rows if r["kernel"] == k and r["config"] == c
                        and r["variant"] == variant), None) for c in configs]
            if any(y is not None for y in ys):
                ax1.plot(configs, ys, marker="o", label=variant)
            ms = [next((r["dcache_miss_rate"] for r in rows if r["kernel"] == k and r["config"] == c
                        and r["variant"] == variant), None) for c in configs]
            if any(m is not None for m in ms):
                ax2.plot(configs, ms, marker="o", label=variant)
        ax1.set_title(f"{k}: cycles"), ax1.set_ylabel("cycles"), ax1.legend()
        ax2.set_title(f"{k}: D-cache miss rate"), ax2.set_ylabel("misses / access"), ax2.legend()
        for ax in (ax1, ax2):
            ax.tick_params(axis="x", rotation=30)
        fig.tight_layout()
        fig.savefig(out / f"{k}.png", dpi=110)
        plt.close(fig)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--configs", help="comma-separated names from tools/cache_configs.json")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--config-file", type=Path, default=REPO / "tools" / "cache_configs.json")
    ap.add_argument("--mem-latency", type=int, default=FROZEN_MEM_LATENCY)
    ap.add_argument("--budget-kib", type=float, default=DEFAULT_BUDGET_KIB)
    ap.add_argument("-j", "--jobs", type=int, default=8)
    ap.add_argument("--timeout", type=float, default=1800.0)
    ap.add_argument("--out", type=Path, default=REPO / "sweep_out")
    a = ap.parse_args()

    if a.mem_latency != FROZEN_MEM_LATENCY:
        print(f"WARNING: memory latency {a.mem_latency} differs from the frozen value "
              f"{FROZEN_MEM_LATENCY}; results are not valid for submission.")
    allc = json.loads(a.config_file.read_text())["configs"]
    chosen = allc if a.all else [c for c in allc if c["name"] in (a.configs or "").split(",")]
    if not chosen:
        ap.error("select configurations with --configs or --all")
    subprocess.run(["make", "-C", str(REPO / "tests"), f"-j{a.jobs}"], check=False)
    a.out.mkdir(parents=True, exist_ok=True)
    rows = []
    for cfg in chosen:
        kib = total_kib(cfg)
        print(f"[sweep] {cfg['name']}: {kib:.2f} KiB L1 storage "
              f"({'within' if kib <= a.budget_kib else 'OVER'} budget {a.budget_kib} KiB)")
        ver = build(cfg, a.mem_latency, a.jobs, a.out)
        if ver is None:
            continue
        for r in run_kernels(cfg, ver, a.out, a.timeout, a.jobs):
            r["l1_kib"] = round(kib, 2)
            r["within_budget"] = kib <= a.budget_kib
            rows.append(r)
    if rows:
        with open(a.out / "results.csv", "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
        plot(rows, a.out)
    print(f"[sweep] {len(rows)} rows -> {a.out / 'results.csv'}")


if __name__ == "__main__":
    main()
